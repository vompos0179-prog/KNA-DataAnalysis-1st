import numpy as np

# ==========================================
# 실습 1. 특정 센서·구간 추출하기
# ==========================================

# 회전수 측정값 배열
rpm = np.array([1800, 1850, 1900, 1950, 2000, 1750])

# 첫 번째 값
print("첫 번째 회전수:", rpm[0])

# 마지막 값
print("마지막 회전수:", rpm[-1])

# 앞에서 3개 값
print("앞 구간:", rpm[0:3])

# 두 칸 간격으로 값 추출
print("두 칸 간격:", rpm[::2])


# ==========================================
# 실습 2. 행·열 단위로 추출하기
# ==========================================

# 설비별 회전수와 토크
data = np.array([[1800, 2.1], [1850, 2.3], [1900, 2.5], [1950, 2.2]])

# 특정 설비의 행 추출
print("\n특정 설비:", data[0])

# 회전수 열 추출
print("회전수:", data[:, 0])

# 토크 열 추출
print("토크:", data[:, 1])


# ==========================================
# 실습 3. 센서값 정규화하기
# ==========================================

# 회전수 배열
rpm = np.array([1800, 1850, 1900, 1950, 2000])

# 최솟값과 최댓값
min_value = rpm.min()
max_value = rpm.max()

# 0~1 사이로 정규화
normalized = (rpm - min_value) / (max_value - min_value)

print("\n최솟값:", min_value)
print("최댓값:", max_value)
print("정규화:", normalized)


# ==========================================
# 실습 4. 이상 센서값 필터링하기
# ==========================================

# 회전수와 토크 배열
rpm = np.array([1800, 2500, 1900, 2700, 2000])
torque = np.array([2.5, 2.8, 1.5, 3.0, 2.2])

# 회전수가 2400보다 큰 값
high_rpm = rpm[rpm > 2400]

# 회전수가 2400보다 크거나
# 토크가 2.0보다 작은 위험 조건
danger = rpm[(rpm > 2400) | (torque < 2.0)]

print("\n기준 초과 회전수:", high_rpm)
print("위험 조건 회전수:", danger)


# ==========================================
# 실습 5. 조건별 개수와 비율 세기
# ==========================================

# 토크 배열
torque = np.array([2.5, 2.8, 1.5, 3.0, 2.2])

# 토크가 2.5보다 큰지 확인
condition = torque > 2.5

# 조건을 만족하는 개수
count = condition.sum()

# 전체 대비 비율
ratio = condition.mean()

print("\n조건 만족 개수:", count)
print("조건 만족 비율:", ratio)


# ==========================================
# 실습 6. 센서별 기초 통계 구하기
# ==========================================

# 여러 설비의 회전수와 토크
sensor_data = np.array(
    [[1800, 2.1], [1850, 2.3], [1900, 2.5], [1950, 2.2], [2000, 2.4]]
)

# 센서별 평균
mean = sensor_data.mean(axis=0)

# 센서별 표준편차
std = sensor_data.std(axis=0)

print("\n센서별 평균:", mean)
print("센서별 표준편차:", std)

# ==========================================
# 실습 8. 필터링과 통계 결합하기
# ==========================================

# 토크 배열
torque = np.array([1.8, 2.1, 2.5, 2.8, 3.0, 2.2])

# 토크가 2.5보다 큰 값만 추출
high_torque = torque[torque > 2.5]

# 추출한 값의 평균
mean = high_torque.mean()

# 추출한 값의 개수
count = high_torque.size

print("\n기준 초과 토크:", high_torque)
print("기준 초과 토크 평균:", mean)
print("기준 초과 토크 개수:", count)


# ==========================================
# 실습 9. NumPy 기초 종합 분석
# ==========================================

# 회전수와 토크 데이터
machine_data = np.array(
    [[1800, 2.1], [1850, 2.3], [1900, 2.5], [1700, 2.2], [1750, 2.4], [2000, 2.6]]
)

# 데이터 구조 확인
print("\n데이터 형태:", machine_data.shape)
print("데이터 자료형:", machine_data.dtype)

# 회전수 열 추출
rpm = machine_data[:, 0]

# 기준보다 낮은 회전수 필터링
abnormal = rpm[rpm < 1800]

# 이상 시점 개수
count = abnormal.size

# 이상 회전수 평균
mean = abnormal.mean()

print("이상 회전수:", abnormal)
print("이상 시점 개수:", count)
print("이상 시점 평균 회전수:", mean)
