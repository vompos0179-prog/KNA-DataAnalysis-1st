# 함수가 호출되면 그 안의 코드는 매번 새롭게 시작된다.
def show_counter():
    count = 0
    print(count)
    # 이 함수가 종료되면 count라는 변수는 사라진다. (함수 안에서 정의된 변수는 함수가 종료되면 사라진다.)


show_counter()  # 0


# 작업이 여러개라면 여러개의 함수를 가진다.
## 각 함수의 이름은 이름에 걸맞는 기능을 수행하도록 정의
def show_student():
    print("학생1: 짱구")
    print("학생2: 철수")
    print("학생3: 훈이")


def show_teacher():
    print("선생님 : 채성아")


def show_classroom():
    show_student()
    show_teacher()


# show_student()  # 학생1: 짱구 // 학생2: 철수 // 학생3: 훈이 // 선생님 : 채성아
# # >> 내부 print에 선생님이라는 항목이 생겨서 학생만 출력 할 수 없게 되었다. (함수의 이름과 기능이 맞지 않음)
# show_teacher() #  # 선생님 : 채성아

# >> 학생과 선생의 명부를 따로 함수를 걸지 않고 상위의 함수를 걸어 같이 출력되게 함.
show_classroom()

