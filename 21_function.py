# Error의 종류
# 1. 실행중의 오류 : runtime Error(작동 중단)
# 2. 논리적 오류 : logical Error(작동은 하지만, 원하는 결과가 나오지 않음)
# 3. 문법적 오류 : syntax Error(코드 작성 중 오류 발생)
# 4. 예외 처리 : exception Error(코드 작성 중 오류 발생, try, except 구문으로 처리 가능)
# 5. NameError : 정의되지 않은 변수, 함수, 클래스 등을 호출할 때 발생
# 6. TypeError : 데이터 타입이 맞지 않을 때 발생
# 7. ValueError : 데이터 값이 맞지 않을 때 발생
# 8. IndexError : 리스트, 튜플, 문자열 등에서 인덱스 범위를 벗어날 때 발생
# 9. KeyError : 딕셔너리에서 존재하지 않는 key를 호출할 때 발생
# 10. AttributeError : 존재하지 않는 속성(함수, 변수 등)을 호출할 때 발생
