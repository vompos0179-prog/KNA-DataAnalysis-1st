# "a".join(parts) 로 a에 어떤것이 오냐에 따라 구분자를 넣어서 출력해준다.
# 모든 요소가 합쳐져서 하나의 문자열로 출력해준다.
# 문자열만 가능하며, 숫자가 들어갈 경우 오류가 출력된다.(str로 형 변환을 꼭 해준다.)

# "========================================================="
print("============sep,end=============")

# sep = A (A로 설정한 문자열이 공백 대신 들어간다.)
print("a","b",sep="-") # "a-b"

# end = B (B로 설정한 문자열이 공백 대신 들어간다.)
print("안녕","하세",end="요") # 안녕 하세요
## end 이후 + 로 문자열을 붙이는 것은 가능하다.

