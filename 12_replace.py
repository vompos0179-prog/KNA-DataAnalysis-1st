print("============.list=============")

# 출력 값 [ ]의 내부 단어를 글자 하나하나가 아니라 단어로 인덱스 번호가 부여됨.
text = "아메리카노 에스프레소 카페라떼"
print(text.split()) # ['아메리카노', '에스프레소', '카페라떼']으로 0번은 아메리카노가 된다.
## 출력된 [ ] 내부의 객체들은 향후 목적에 맞게 다시 함수를 쓰며 활용을 할 수 있다.

text_list = text.split()
print(text_list) # ['아메리카노', '에스프레소', '카페라떼'] 중 에스프레소만 출력 하고 싶다.
print(text_list[1]) ## 인덱스 번호는 음수도 똑같이 출력한다. 

# split(" ") " " 내부에 들어있는 특정 단어를 기준으로 나눠준다. (정확한 특정 단어만 인식하며 리스트화 한다.)

# split 의 횟수 제한
num = "010-1234-1234" # ["010","1234-1234"] 의 결과를 얻고 싶다.
print(num.split("-",1))

