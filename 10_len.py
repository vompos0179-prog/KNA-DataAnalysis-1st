print("============in=============")

# 특정 단어가 문장에 포함되어있는지 True, False 로 출력함.
# in(포함 여부) <> not in (불포함 여부)
# 중요 로그 혹은 문장에서 위험 키워드를 검색해 포함 미포함 여부를 확인

print("고장" in "설비 고장 발생") # True
print("정상" in "설비 고장 발생") # False
print("설비에서 고장" in "설비 고장 발생") # False
print("설비에서 고장" in "설비에서 고장이 발생했습니다") # True

# not in 은 in의 정반대 동작

print("고장" not in "설비 고장 발생") # False
print("정상" not in "설비 고장 발생") # True
print("설비에서 고장" not in "설비 고장 발생") # True
print("설비에서 고장" not in "설비에서 고장이 발생했습니다") # False

