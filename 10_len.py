print("============.index=============")

# 특정 문자열의 위치(인덱스 번호)를 반환
# find 와 index가 다른점은 찾고나서 없을때, 멈추는 가에 따라 다르다.
# 찾는 문자열이 없으면 -1을 출력하는 find 와 다르게 Error가 발생한다.

email = "vompos@naver.com"
at = email.index("@") # 5
print(email[0:at]) # vompos
print(email[:at]) # vompos
print(email[at:]) # @naver.com
print(email[at+1:]) # naver.com

