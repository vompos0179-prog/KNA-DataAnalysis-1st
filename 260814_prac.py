import pandas as pd

# ============================================================
# 데이터 불러오기
# ============================================================

# 주조 다이캐스팅 전체 데이터 불러오기
# utf-8-sig : 한글 CSV 파일을 안전하게 읽기 위한 인코딩
df = pd.read_csv("data/13_diecasting_shot.csv", encoding="utf-8-sig")

print("=" * 60)
print("데이터 불러오기")
print("=" * 60)

print(df.head())
print()


# ============================================================
# 실습 1. 조건 필터링
# ============================================================

print("=" * 60)
print("실습 1. 조건 필터링")
print("=" * 60)

# 비스킷두께가 13 이상인 데이터만 선택
thick = df[df["비스킷두께"] >= 13]

print("비스킷두께가 13 이상인 데이터")
print(thick)

print("데이터 개수:", len(thick))
print()


# ============================================================
# 실습 2. 복합 조건
# ============================================================

print("=" * 60)
print("실습 2. 복합 조건")
print("=" * 60)

# 비스킷두께가 13 이상이고
# 사이클타임이 25 이상인 데이터
both = df[(df["비스킷두께"] >= 13) & (df["사이클타임"] >= 25)]

print("두 조건을 모두 만족하는 데이터")
print(both)

print("데이터 개수:", len(both))
print()


# ============================================================
# 실습 3. OR 조건
# ============================================================

print("=" * 60)
print("실습 3. OR 조건")
print("=" * 60)

# 비스킷두께가 13 이상이거나
# 사이클타임이 25 이상인 데이터
either = df[(df["비스킷두께"] >= 13) | (df["사이클타임"] >= 25)]

print("둘 중 하나라도 만족하는 데이터")
print(either)

print("데이터 개수:", len(either))
print()


# ============================================================
# 실습 4. isin과 between
# ============================================================

print("=" * 60)
print("실습 4. isin과 between")
print("=" * 60)

# 품질등급이 양품 또는 주의인 데이터
quality_data = df[df["품질등급"].isin(["양품", "주의"])]

print("품질등급이 양품 또는 주의인 데이터")
print(quality_data.head())
print()

# 비스킷두께가 10 이상 20 이하인 데이터
thickness_range = df[df["비스킷두께"].between(10, 20)]

print("비스킷두께가 10 이상 20 이하인 데이터")
print(thickness_range.head())
print()
