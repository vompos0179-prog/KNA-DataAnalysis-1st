import pandas as pd

# ============================================================
# 데이터 불러오기
# ============================================================

# 주조 다이캐스팅 전체 데이터 불러오기
# utf-8-sig : 한글 CSV 파일을 안전하게 읽기 위한 인코딩
df = pd.read_csv("data/13_diecasting_shot.csv", encoding="utf-8-sig")

print("=" * 60)
print("데이터 불러오기")
print("=" * 60)

print(df.head())
print()


# ============================================================
# 실습 1. 조건 필터링
# ============================================================

print("=" * 60)
print("실습 1. 조건 필터링")
print("=" * 60)

# 비스킷두께가 13 이상인 데이터만 선택
thick = df[df["비스킷두께"] >= 13]

print("비스킷두께가 13 이상인 데이터")
print(thick)

print("데이터 개수:", len(thick))
print()


# ============================================================
# 실습 2. 복합 조건
# ============================================================

print("=" * 60)
print("실습 2. 복합 조건")
print("=" * 60)

# 비스킷두께가 13 이상이고
# 사이클타임이 25 이상인 데이터
both = df[(df["비스킷두께"] >= 13) & (df["사이클타임"] >= 25)]

print("두 조건을 모두 만족하는 데이터")
print(both)

print("데이터 개수:", len(both))
print()


# ============================================================
# 실습 3. OR 조건
# ============================================================

print("=" * 60)
print("실습 3. OR 조건")
print("=" * 60)

# 비스킷두께가 13 이상이거나
# 사이클타임이 25 이상인 데이터
either = df[(df["비스킷두께"] >= 13) | (df["사이클타임"] >= 25)]

print("둘 중 하나라도 만족하는 데이터")
print(either)

print("데이터 개수:", len(either))
print()


# ============================================================
# 실습 4. isin과 between
# ============================================================

print("=" * 60)
print("실습 4. isin과 between")
print("=" * 60)

# 품질등급이 양품 또는 주의인 데이터
quality_data = df[df["품질등급"].isin(["양품", "주의"])]

print("품질등급이 양품 또는 주의인 데이터")
print(quality_data.head())
print()

# 비스킷두께가 10 이상 20 이하인 데이터
thickness_range = df[df["비스킷두께"].between(10, 20)]

print("비스킷두께가 10 이상 20 이하인 데이터")
print(thickness_range.head())
print()


# ============================================================
# 실습 5. 위험 순으로 정렬하기
# ============================================================

print("=" * 60)
print("실습 5. 위험 순으로 정렬하기")
print("=" * 60)

# 비스킷두께가 큰 순서대로 정렬
sorted_data = df.sort_values("비스킷두께", ascending=False)

# 가장 큰 5개만 확인
top5 = sorted_data.head(5)

print("비스킷두께가 큰 상위 5개")
print(top5)

print()

# 여러 열을 기준으로 정렬
# 품질등급을 먼저 정렬하고
# 같은 품질등급 안에서는 사이클타임을 정렬
multi_sorted = df.sort_values(["품질등급", "사이클타임"], ascending=[True, False])

print("다중 정렬 결과")
print(multi_sorted.head())

print()


# ============================================================
# 실습 6. 필터링과 정렬 연결
# ============================================================

print("=" * 60)
print("실습 6. 필터링과 정렬 연결")
print("=" * 60)

# 품질등급이 불량인 데이터만 먼저 선택
# 그 다음 비스킷두께가 큰 순서대로 정렬
# 마지막으로 상위 5개만 선택
danger = df[df["품질등급"] == "불량"].sort_values("비스킷두께", ascending=False).head(5)

print("불량 데이터 중 비스킷두께가 큰 상위 5개")
print(danger)

print()


# ============================================================
# 실습 7. 이상 의심 설비 리포트
# ============================================================

print("=" * 60)
print("실습 7. 이상 의심 설비 리포트")
print("=" * 60)

# 비스킷두께가 13 이상이고
# 사이클타임이 25 이상인 위험 데이터를 선택
risk = df[(df["비스킷두께"] >= 13) & (df["사이클타임"] >= 25)].sort_values(
    "비스킷두께", ascending=False
)

# 필요한 주요 열만 선택
risk_report = risk[["샷", "비스킷두께", "사이클타임", "품질등급"]]

print("위험 설비 데이터")
print(risk_report)

print()
print("위험 데이터 개수:", len(risk_report))

# 가장 위험한 데이터 확인
if len(risk_report) > 0:

    most_dangerous = risk_report.iloc[0]

    print()
    print("가장 위험한 샷")
    print("샷 번호:", most_dangerous["샷"])
    print("비스킷두께:", most_dangerous["비스킷두께"])
    print("사이클타임:", most_dangerous["사이클타임"])
    print("품질등급:", most_dangerous["품질등급"])

print()


