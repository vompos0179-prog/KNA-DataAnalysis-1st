import pandas as pd

df = pd.read_csv("data/13_diecasting_shot.csv", encoding="utf-8-sig")

# ============================================================
# 실습 5. 위험 순으로 정렬하기
# ============================================================

print("=" * 60)
print("실습 5. 위험 순으로 정렬하기")
print("=" * 60)

# 비스킷두께가 큰 순서대로 정렬
sorted_data = df.sort_values("비스킷두께", ascending=False)

# 가장 큰 5개만 확인
top5 = sorted_data.head(5)

print("비스킷두께가 큰 상위 5개")
print(top5)

print()

# 여러 열을 기준으로 정렬
# 품질등급을 먼저 정렬하고
# 같은 품질등급 안에서는 사이클타임을 정렬
multi_sorted = df.sort_values(["품질등급", "사이클타임"], ascending=[True, False])

print("다중 정렬 결과")
print(multi_sorted.head())

print()


# ============================================================
# 실습 6. 필터링과 정렬 연결
# ============================================================

print("=" * 60)
print("실습 6. 필터링과 정렬 연결")
print("=" * 60)

# 품질등급이 불량인 데이터만 먼저 선택
# 그 다음 비스킷두께가 큰 순서대로 정렬
# 마지막으로 상위 5개만 선택
danger = df[df["품질등급"] == "불량"].sort_values("비스킷두께", ascending=False).head(5)

print("불량 데이터 중 비스킷두께가 큰 상위 5개")
print(danger)

print()

