import numpy as np

# ==========================================
# 실습 1. 센서값 배열 만들기
# ==========================================

# 섭씨 센서값 리스트
celsius = [20, 25, 30, 35]

# 리스트를 NumPy 배열로 만들기
temp = np.array(celsius)

# 섭씨 → 화씨 변환
fahrenheit = temp * 9 / 5 + 32

# 결과 출력
print("실습 1")
print("섭씨:", temp)
print("화씨:", fahrenheit)


# ==========================================
# 실습 2. 균등 간격 배열 만들기
# ==========================================

# 0부터 100까지 5개의 값으로 균등하게 나누기
values = np.linspace(0, 100, 5)

# 배열 출력
print("\n실습 2")
print(values)

# 값 사이의 간격 확인
print("간격:", values[1] - values[0])


# ==========================================
# 실습 3. 측정 시간축 배열 만들기
# ==========================================

# 0초부터 10초까지 2초 간격으로 만들기
time = np.arange(0, 11, 2)

# 결과 출력
print("\n실습 3")
print("측정 시간:", time)


# ==========================================
# 실습 4. 배열 구조 확인하기
# ==========================================

# 설비별 측정값을 2차원 배열로 만들기
sensor = np.array([[10, 20, 30], [40, 50, 60]])

# 차원 확인
print("\n실습 4")
print("차원:", sensor.ndim)

# 형태 확인
print("형태:", sensor.shape)

# 전체 개수 확인
print("개수:", sensor.size)


# ==========================================
# 실습 5. 자료형 확인과 변환하기
# ==========================================

# 소수점이 있는 측정값 배열
data = np.array([1.7, 2.3, 3.9])

# 현재 자료형 확인
print("\n실습 5")
print("현재 자료형:", data.dtype)

# 정수형으로 변환
data_int = data.astype(int)

# 변환된 배열 출력
print("정수형 배열:", data_int)


# ==========================================
# 실습 6. 배열 모양 바꾸기
# ==========================================

# 0부터 7까지 8개의 값 생성
numbers = np.arange(8)

# 2행 4열로 변경
numbers_2d = numbers.reshape(2, 4)

# 결과 출력
print("\n실습 6")
print(numbers_2d)


# ==========================================
# 실습 7. 센서 데이터 표로 정리하기
# ==========================================

# 3개 시점 × 2개 센서 = 6개 값
sensor_data = np.arange(6)

# 3행 2열로 변경
sensor_table = sensor_data.reshape(3, 2)

# 결과 출력
print("\n실습 7")
print(sensor_table)


# ==========================================
# 실습 8. 배열 생성부터 정리까지
# ==========================================

# 센서 측정값 배열 생성
measurements = np.array([10.5, 20.5, 30.5, 40.5, 50.5, 60.5])

# 구조 확인
print("\n실습 8")
print("형태:", measurements.shape)
print("자료형:", measurements.dtype)

# 3행 2열로 변경
measurements_table = measurements.reshape(3, 2)

# 결과 출력
print("정리된 배열:")
print(measurements_table)
